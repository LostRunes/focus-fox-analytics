// Writes env.js from environment variables at build time (e.g. on Vercel),
// so keys never live in the repo.
const fs = require('fs');
const path = require('path');

const required = ['SUPABASE_2_URL', 'SUPABASE_2_KEY'];
const missing = required.filter((k) => !process.env[k]);
if (missing.length) {
  console.error(`Missing environment variables: ${missing.join(', ')}`);
  process.exit(1);
}

const env = Object.fromEntries(required.map((k) => [k, process.env[k]]));
fs.writeFileSync(
  path.join(__dirname, '..', 'env.js'),
  `// Generated by scripts/generate-env.js — do not commit\nwindow.ENV = ${JSON.stringify(env, null, 2)};\n`
);
console.log('env.js generated');
